#!/bin/bash
# 诊断尺寸不匹配问题

echo "========================================================================"
echo "诊断图像尺寸变化"
echo "========================================================================"

LOG_FILE="logs/*.log"

echo ""
echo "=== 1. 查找 (472, 420) 这个样本的完整执行过程 ==="
echo "------------------------------------------------------------------------"

# 查找涉及 472 或 420 的日志
echo "查找尺寸相关的日志..."
grep -n "472\|420" $LOG_FILE 2>/dev/null | head -30

echo ""
echo "=== 2. 查找工具输入尺寸 ==="
echo "------------------------------------------------------------------------"
grep "📏 工具输入图像尺寸" $LOG_FILE 2>/dev/null | head -10

echo ""
echo "=== 3. 查找工具是否改变尺寸 ==="
echo "------------------------------------------------------------------------"
grep "改变了尺寸" $LOG_FILE 2>/dev/null | head -10

echo ""
echo "=== 4. 查找工具保持尺寸的情况 ==="
echo "------------------------------------------------------------------------"
grep "保持尺寸" $LOG_FILE 2>/dev/null | head -10

echo ""
echo "=== 5. 查找具体样本的env_name ==="
echo "------------------------------------------------------------------------"
# 查找复原图尺寸为(472, 420)附近的样本信息
echo "查找相关样本的退化类型..."
grep -B20 "复原图.*472\|复原图.*420" $LOG_FILE 2>/dev/null | grep "env_name\|reward_model" | head -10

echo ""
echo "=== 6. 查找工具链执行情况 ==="
echo "------------------------------------------------------------------------"
grep "工具链执行完成" $LOG_FILE 2>/dev/null | head -10

echo ""
echo "========================================================================"
echo "诊断完成"
echo "========================================================================"

echo ""
echo "💡 关键问题:"
echo "  如果数据集中所有low resolution样本都是4倍关系，"
echo "  但训练中看到的不是4倍，说明："
echo "  1. 工具处理改变了尺寸（检查'改变了尺寸'日志）"
echo "  2. 或者这不是low resolution样本"
echo "  3. 或者SR工具已经执行过（部分放大了）"
echo ""
echo "下一步: 查看上面的日志，找到这个样本的完整执行过程"

